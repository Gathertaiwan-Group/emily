  settings    jsonb not null default '{}'::jsonb,  -- public messages / labels only; CRM integration secrets live in site_emily.settings (is_public=false)
  pages       text[] not null default '{}',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create table if not exists site_emily.form_submissions (
  id          bigint generated always as identity primary key,
  form_id     bigint not null references site_emily.forms(id) on delete cascade,
  data        jsonb not null,
  status      text not null default 'new' check (status in ('new','read','spam','trash')),
  page_url    text,
  ip          inet,
  user_agent  text,
  created_at  timestamptz not null default now()
);
create index if not exists form_submissions_form_idx on site_emily.form_submissions (form_id, created_at desc);

-- ---------------------------------------------------------------- redirects
create table if not exists site_emily.redirects (
  id          bigint generated always as identity primary key,
  source_path text not null unique,          -- decoded path, no trailing slash, e.g. /some-attachment-slug
  target      text not null,                 -- relative path or absolute URL
  status_code smallint not null default 301 check (status_code in (301,302,307,308,410)),
  kind        text not null default 'manual', -- attachment | legacy | manual
  hits        bigint not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- updated_at triggers
do $$
declare t text;
begin
  foreach t in array array['settings','authors','media','terms','posts','menus','products','product_variations',
                           'quantity_discount_rules','customers','coupons','carts','orders','forms']
  loop
    execute format('drop trigger if exists %I on site_emily.%I', t || '_touch', t);
    execute format('create trigger %I before update on site_emily.%I for each row execute function site_emily.touch_updated_at()', t || '_touch', t);
  end loop;
end $$;
