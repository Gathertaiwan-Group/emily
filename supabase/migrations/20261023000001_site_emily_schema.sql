-- site_emily: data model for "The three of us" (loveccdd.com) migrated from WordPress + WooCommerce.
-- Every object is schema-qualified with site_emily. Old WordPress IDs are kept as primary keys
-- (identity columns start high so new rows never collide with IDs imported later from the DB backup).

-- ---------------------------------------------------------------- helpers
create or replace function site_emily.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

-- ---------------------------------------------------------------- admins / audit
create table if not exists site_emily.admins (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  email       text not null,
  role        text not null default 'administrator' check (role in ('administrator','editor','shop_manager','author')),
  display_name text,
  created_at  timestamptz not null default now()
);

create or replace function site_emily.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from site_emily.admins a where a.user_id = auth.uid());
$$;

create table if not exists site_emily.audit_log (
  id          bigint generated always as identity primary key,
  at          timestamptz not null default now(),
  actor       text not null,                -- admin email / 'mcp' / 'import'
  actor_user_id uuid,
  source      text not null default 'admin' check (source in ('admin','mcp','import','system','storefront')),
  action      text not null,                -- e.g. post.update, product.price, order.status
  entity_type text not null,
  entity_id   text,
  before      jsonb,
  after       jsonb,
  ip          inet,
  user_agent  text
);
create index if not exists audit_log_entity_idx on site_emily.audit_log (entity_type, entity_id);
create index if not exists audit_log_at_idx on site_emily.audit_log (at desc);

