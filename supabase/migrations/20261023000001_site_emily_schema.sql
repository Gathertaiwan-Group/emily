  media_id    bigint not null references site_emily.media(id) on delete cascade,
  kind        text not null check (kind in ('original','scaled','rotated','variant','duplicate')),
  new_url     text not null
);
create index if not exists media_url_map_media_idx on site_emily.media_url_map (media_id);

