import { db } from "@/lib/db";
import { encPath } from "@/lib/format";
import { getAllProducts, getTerms } from "@/lib/data";
import { SITE_URL } from "@/lib/site";

export const dynamic = "force-dynamic";
const PER = 200; // Rank Math default entries per sitemap

const xmlHead = `<?xml version="1.0" encoding="UTF-8"?>`;
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const loc = (p: string) => esc(SITE_URL + (p === "/" ? "/" : encPath(p)));
const iso = (d?: string | null) => (d ? new Date(d).toISOString().replace(/\.\d{3}Z$/, "+00:00") : "");

async function publishedPosts(type: string) {
  const rows: any[] = [];
  for (let from = 0; ; from += 1000) {
    const r = await db().from("posts").select("id,link_path,modified,date,seo,featured_media_id").eq("status", "publish").eq("post_type", type).order("date", { ascending: false }).range(from, from + 999);
    rows.push(...(r.data ?? []));
    if ((r.data ?? []).length < 1000) break;
  }
  return rows.filter((p) => !String(p.seo?.robots ?? "").includes("noindex"));
}

function urlset(entries: { loc: string; lastmod?: string; image?: string }[]) {
  const body = entries
    .map((e) => `\t<url>\n\t\t<loc>${e.loc}</loc>\n${e.lastmod ? `\t\t<lastmod>${e.lastmod}</lastmod>\n` : ""}${e.image ? `\t\t<image:image>\n\t\t\t<image:loc>${esc(e.image)}</image:loc>\n\t\t</image:image>\n` : ""}\t</url>`)
    .join("\n");
  return `${xmlHead}\n<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n<!-- XML Sitemap generated by the Next.js storefront (Rank Math compatible layout) -->`;
}

const xml = (s: string, status = 200) => new Response(s, { status, headers: { "content-type": "application/xml; charset=UTF-8", "x-robots-tag": "noindex, follow" } });

export async function GET(_req: Request, ctx: { params: Promise<{ name: string }> }) {
  const { name } = await ctx.params;
  if (name === "index") {
    const [posts, pages, products, { all }] = await Promise.all([publishedPosts("post"), publishedPosts("page"), getAllProducts(), getTerms()]);
    const maps: { loc: string; lastmod: string }[] = [];
    for (let i = 0; i * PER < posts.length; i++) maps.push({ loc: `${SITE_URL}/post-sitemap${i + 1}.xml`, lastmod: iso(posts[i * PER]?.modified) });
    maps.push({ loc: `${SITE_URL}/page-sitemap.xml`, lastmod: iso(pages.map((p) => p.modified).sort().pop()) });
    if (products.length) maps.push({ loc: `${SITE_URL}/product-sitemap.xml`, lastmod: iso(products.map((p) => p.modified).sort().pop()) });
    if (all.some((t) => t.taxonomy === "category" && t.count > 0)) maps.push({ loc: `${SITE_URL}/category-sitemap.xml`, lastmod: iso(posts[0]?.modified) });
    const body = maps.map((m) => `\t<sitemap>\n\t\t<loc>${esc(m.loc)}</loc>\n\t\t<lastmod>${m.lastmod}</lastmod>\n\t</sitemap>`).join("\n");
    return xml(`${xmlHead}\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</sitemapindex>`);
  }
  const m = /^(post|page|product|category)-(\d*)$/.exec(name);
  if (!m) return xml(`${xmlHead}<error>not found</error>`, 404);
  const [, type, nRaw] = m;
  const n = Number(nRaw || 1);
  if (type === "post") {
    const posts = await publishedPosts("post");
    const slice = posts.slice((n - 1) * PER, n * PER);
    if (!slice.length) return xml(`${xmlHead}<error>not found</error>`, 404);
    const media = await db().from("media").select("id,public_url").in("id", slice.map((p) => p.featured_media_id).filter(Boolean));
    const mm = new Map((media.data ?? []).map((x: any) => [x.id, x.public_url]));
    return xml(urlset(slice.map((p) => ({ loc: loc(p.link_path), lastmod: iso(p.modified), image: mm.get(p.featured_media_id) as string | undefined }))));
  }
  if (type === "page") {
    const pages = await publishedPosts("page");
    const home = { loc: `${SITE_URL}/`, lastmod: "" };
    return xml(urlset([home, ...pages.filter((p) => p.link_path !== "/").map((p) => ({ loc: loc(p.link_path), lastmod: iso(p.modified) }))]));
  }
  if (type === "product") {
    const products = (await getAllProducts()).filter((p) => p.catalog_visibility !== "hidden" && !String(p.seo?.robots ?? "").includes("noindex"));
    return xml(urlset([{ loc: `${SITE_URL}/shop`, lastmod: "" }, ...products.map((p) => ({ loc: loc(p.link_path), lastmod: iso(p.modified), image: p.image?.public_url }))]));
  }
  const { all } = await getTerms();
  const cats = all.filter((t) => t.taxonomy === "category" && t.count > 0 && t.link_path && !String(t.seo?.robots ?? "").includes("noindex"));
  return xml(urlset(cats.map((t) => ({ loc: loc(t.link_path!) }))));
}
