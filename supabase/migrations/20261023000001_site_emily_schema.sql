-- ---------------------------------------------------------------- media
create table if not exists site_emily.media (
  id            bigint generated by default as identity (start with 100000000) primary key, -- = attachment post ID when known
  wp_id         bigint unique,               -- null for files found only by HTML scan (attachment metadata private)
  slug          text,
  title         text not null default '',
  caption       text not null default '',
  description   text not null default '',
  alt_text      text not null default '',
  mime_type     text not null,               -- mime of the stored file (image/webp after conversion)
  original_mime_type text,
  media_type    text not null default 'image' check (media_type in ('image','video','audio','file')),
  width         int,
  height        int,
  filesize      bigint,                      -- bytes of stored file
  original_filesize bigint,
  parent_post_id bigint,                     -- post_parent (may point to a private post)
  author_id     bigint,
  status        text not null default 'inherit',
  date          timestamptz,
  modified      timestamptz,
  old_file      text not null,               -- WP relative path: YYYY/MM/name.ext (original, without -scaled)
  old_url       text not null,               -- canonical old URL (as WP reported source_url)
  storage_path  text not null,               -- path inside bucket site-emily (byte-identical duplicates share one file)
  public_url    text not null,
  link_path     text,                        -- old attachment page path (301 -> public_url)
  sha1          text,                        -- of source file used for conversion
  converted     boolean not null default false,
  metadata_source text not null default 'rest' check (metadata_source in ('rest','html_scan','db')),
  sizes         jsonb,                       -- original WP media_details.sizes (for reference)
  meta          jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists media_old_file_idx on site_emily.media (old_file);
create index if not exists media_parent_idx on site_emily.media (parent_post_id);
create index if not exists media_storage_path_idx on site_emily.media (storage_path);

-- every old URL (original, -scaled, -WxH variants, legacy domain) -> new URL
